#!/usr/bin/env python3
"""Shared manifest for every code generator under ``scripts/``.

This module is the single, machine-readable source of truth for the three
generators (``generate_vpi_attr.py``, ``generate_sv_export.py`` and
``gen_stub.py``).  It deliberately has no third-party dependency so CMake, the
generators and the reproducibility guard can all import it with a plain
``import gen_manifest``.

Layout of the manifest:

* ``VPI_ATTR_*``  - macro source headers, extraction pattern and render template
                    for the gitignored ``inc/vpi_attr.h``.
* ``SV_EXPORT_*`` - the tracked SystemVerilog package, the stable include line
                    that replaces the former in-place generated region, the
                    excluded task/function list, and the build-directory output
                    names.
* ``PYI_*``       - the stub module plus the classes/constants that must be
                    present in the generated ``.pyi`` files (validation only;
                    nanobind's stubgen still discovers the bindings itself).
* ``DPI_STUB_*``  - placeholder for the DPI export stub section, which is
                    currently hand-frozen in ``inc/dpi_stub.c``.
"""

from pathlib import Path

SCHEMA_VERSION = 1

# ---------------------------------------------------------------------------
# inc/vpi_attr.h (gitignored; generated in place, as before)
# ---------------------------------------------------------------------------
VPI_ATTR_SOURCE_HEADERS = ("vpi_user.h", "sv_vpi_user.h")
VPI_ATTR_MACRO_PATTERN = r"#define\s+(vpi\w+|cb\w+)\s+(\d+)"
VPI_ATTR_TEMPLATE = 'vpi.attr("{name}") = {name};'
VPI_ATTR_OUTPUT = ("inc", "vpi_attr.h")

# ---------------------------------------------------------------------------
# SV DPI-C export declarations (build directory; never written back to the
# tracked SystemVerilog source).
# ---------------------------------------------------------------------------
SV_EXPORT_SOURCE = ("src", "svuvm", "python_bridge_pkg.sv")
SV_EXPORT_BEGIN_MARKER = "// EXPORT_DPIC_BEGIN"
SV_EXPORT_END_MARKER = "// EXPORT_DPIC_END"
SV_EXPORT_INCLUDE_FILE = "python_bridge_pkg_export.svh"
SV_EXPORT_INCLUDE_LINE = '`include "python_bridge_pkg_export.svh"'
SV_EXPORT_HEADER_FILE = "export_dpi.h"
SV_EXPORT_GENERATED_COMMENTS = (
    "    // Generated by gen_export.py",
    "    // Do not edit this file manually",
)
# The legacy generator interpolated ``str(member.prototype.name)``, whose
# pyslang rendering carries one leading space.  These prefixes include that
# space so the .svh stays byte-identical to the old in-place region.
SV_EXPORT_TASK_PREFIX = '    export "DPI-C" task      '
SV_EXPORT_FUNCTION_PREFIX = '    export "DPI-C" function  '
SV_EXPORT_DECL_SUFFIX = ";"

# Tasks/functions declared in the package but not exported to DPI-C.  Kept
# verbatim from the original generator so the generated declarations are
# byte-for-byte identical to the legacy export region.
SV_EXPORT_EXCLUDE_FUNC_LIST = (
    "py_func",
    "call_py_func",
    "get_contxt",
    "base16_encode",
    "base16_decode",
    "wait_trigger_data",
    "wait_ptrigger_data",
    "get_trigger_data",
    "get_default_data",
    "set_default_data",
    "set_config_int_array_t",
    "get_config_int_array_t",
    "set_config_byte_array_t",
    "get_config_byte_array_t",
)

# ---------------------------------------------------------------------------
# Python stubs: stubgen discovers bindings; the manifest records the expected
# classes/constants so gen_stub.py can validate its output.
# ---------------------------------------------------------------------------
PYI_MODULE = "_svuvm"
PYI_RECURSIVE = True
PYI_ROOT_FILE = "__init__.pyi"
PYI_VPI_FILE = "vpi.pyi"
PYI_ROOT_CLASSES = (
    "SimulatorCapabilities",
    "BridgeError",
    "BridgeInvalidArgument",
    "BridgeOutOfRange",
    "BridgeUnsupported",
)
PYI_VPI_CLASSES = (
    "VpiTime",
    "VpiDelay",
    "VpiVecVal",
    "VpiStrengthVal",
    "VpiValue",
    "VpiArrayValue",
    "VpiSystfData",
    "VpiVlogInfo",
    "VpiErrorInfo",
    "CbData",
)
PYI_EXPECTED_CLASSES = PYI_ROOT_CLASSES + PYI_VPI_CLASSES
PYI_EXPECTED_CONSTANTS = (
    "UVM_INFO",
    "UVM_WARNING",
    "UVM_ERROR",
    "UVM_FATAL",
    "UVM_NONE",
    "UVM_LOW",
    "UVM_MEDIUM",
    "UVM_HIGH",
    "UVM_FULL",
    "UVM_DEBUG",
    "UVM_NO_ACTION",
    "UVM_DISPLAY",
    "UVM_LOG",
    "UVM_COUNT",
    "UVM_EXIT",
    "UVM_CALL_HOOK",
    "UVM_STOP",
    "UVM_RM_RECORD",
)

# ---------------------------------------------------------------------------
# dpi_stub: 待纳管。
# scripts/generate_dpi_stub.py 在本仓库中不存在（已核实），inc/dpi_stub.c 的
# "DPI Export stubs (from SystemVerilog to C++)" 段是手工固化的。这里只保留
# 纳管位置，不新建脚本、也不驱动任何生成；将来该脚本出现时从这里取配置。
# ---------------------------------------------------------------------------
DPI_STUB_SOURCE = ("inc", "dpi_stub.c")
DPI_STUB_GENERATOR = None
DPI_STUB_NOTE = (
    "pending: scripts/generate_dpi_stub.py does not exist; the DPI export "
    "stub section in inc/dpi_stub.c is hand-frozen."
)


def source_package(root):
    """Return the tracked SystemVerilog package path under ``root``."""
    return Path(root).joinpath(*SV_EXPORT_SOURCE)


def vpi_attr_output(root):
    """Return the default vpi_attr.h output path under ``root``."""
    return Path(root).joinpath(*VPI_ATTR_OUTPUT)
