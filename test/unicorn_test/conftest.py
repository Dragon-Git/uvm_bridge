"""Thin pytest driver for the unicorn firmware register-access test.

All logic lives in :mod:`ral_common`; this module only declares which sources,
incdirs, entry point, generated artefacts and environment this suite needs,
then binds the shared hooks. The simulator-side ``reg_test.py`` is a simulator
module, not a pytest module, so it is excluded by name.

The firmware is generated by the shared artifact fixture at build/fw.bin and
injected as ``UNICORN_TEST_FW`` (and the shared ``FW_REG_IMAGE``), replacing
the deleted Makefile's absolute path export.
"""

from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
TEST_ROOT = HERE.parent

# ral_common is a package under test/, not under this directory.
if str(TEST_ROOT) not in sys.path:
    sys.path.insert(0, str(TEST_ROOT))

from ral_common import (  # noqa: E402  (sys.path prepared above)
    ArtifactSpec,
    FIRMWARE_CASES,
    RALSuiteSpec,
    SimConfig,
    VerdictPolicy,
    build_driver,
)

SV_DIR = TEST_ROOT / "pyral_test" / "sv"
RDL = TEST_ROOT / "pyral_test" / "demo_regs.rdl"
RTL_DIR = HERE / "rtl"
HEADER_DIR = HERE / "c_header"
BUILD_DIR = HERE / "build"
RTL_MODULE = "demo_reg_block"
FW_IMAGE = BUILD_DIR / "fw.bin"

_DRIVER = build_driver(
    RALSuiteSpec(
        suite="unicorn",
        cases=FIRMWARE_CASES,
        sim=SimConfig(
            test_dir=HERE,
            top_sv=SV_DIR / "top.sv",
            sv_sources=(
                SV_DIR / "apb3_intf.sv",
                SV_DIR / "apb3_intf_driver.sv",
                SV_DIR / "reg_agent_pkg.sv",
                SV_DIR / "reg_seq_pkg.sv",
                RTL_DIR / RTL_MODULE / "demo_regs_pkg.sv",
                RTL_DIR / RTL_MODULE / "demo_regs.sv",
            ),
            incdirs=(SV_DIR, RTL_DIR / RTL_MODULE, HEADER_DIR),
            uvm_testname="reg_test",
            py_dir=str(HERE),
            pythonpath_roots=(TEST_ROOT / "fw", TEST_ROOT),
            # FW_TEST_DONE is printed even on failure by fw.register_access.
            # TEST_PASS/TEST_FAIL stay in the log for manual runs, while the
            # per-case JSON decides which replay test fails.
            completion_marker="FW_TEST_DONE",
            verdict=VerdictPolicy.CasesOnly,
            # Same two benign warnings as pyral: peakrdl packages omit
            # timescales and write struct members from separate blocks.
            verilator_warnings=("-Wno-TIMESCALEMOD", "-Wno-MULTIDRIVEN"),
            extra_env={"UNICORN_TEST_FW": str(FW_IMAGE), "FW_REG_IMAGE": str(FW_IMAGE)},
            build_root=BUILD_DIR,
        ),
        artifacts=ArtifactSpec(
            root=HERE,
            rdl=RDL,
            need_regblock=True,
            need_cheader=True,
            need_firmware=True,
            rtl_dir=RTL_DIR,
            header_dir=HEADER_DIR,
            build_dir=BUILD_DIR,
            rdl_module=RTL_MODULE,
        ),
    )
)

pytest_generate_tests = _DRIVER.pytest_generate_tests
backend_results = _DRIVER.backend_results
artifacts = _DRIVER.artifacts

collect_ignore = ["reg_test.py"]
